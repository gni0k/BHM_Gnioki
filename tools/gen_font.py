#!/usr/bin/env python3
"""
Generates src/font_data.c: anti-aliased 8-bit alpha bitmaps of printable ASCII
(0x20..0x7E) rendered from DejaVu Sans. This is a *development-time* helper only;
the generated C file is committed, so building pcapreport never needs Python.

Usage: python3 tools/gen_font.py [/path/DejaVuSans.ttf] [/path/DejaVuSans-Bold.ttf]
Font licence: DejaVu (Bitstream Vera derivative) - free to use, modify, embed.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

REG = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BLD = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
FONTS = [("font_small", REG, 14), ("font_bold", BLD, 17)]

out = ["/* AUTO-GENERATED by tools/gen_font.py - do not edit by hand.",
       " * Glyphs rasterised from DejaVu Sans (Bitstream Vera licence). */",
       '#include "font.h"', ""]
for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    ch = asc + desc
    adv = [int(round(f.getlength(chr(c)))) for c in range(32, 127)]
    cw = max(max(adv), max(f.getbbox(chr(c))[2] for c in range(32, 127))) + 1
    data = []
    for c in range(32, 127):
        im = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=255)
        data.extend(im.tobytes())
    out.append(f"static const unsigned char {name}_bits[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i+24]) + ",")
    out.append("};")
    out.append(f"static const unsigned char {name}_adv[95] = {{" + ",".join(map(str, adv)) + "};")
    out.append(f"const font_t {name} = {{ {cw}, {ch}, {asc}, {name}_adv, {name}_bits }};")
    out.append("")
open("src/font_data.c", "w").write("\n".join(out))
print("written src/font_data.c")
